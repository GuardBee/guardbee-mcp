// Dalvik executable: only the class descriptors are needed, which come from
// type_ids -> string_ids -> string data (uleb128 length, then MUTF-8 bytes).

function readUleb128(buf: Buffer, p: number): { value: number; next: number } {
  let value = 0;
  let shift = 0;
  let b: number;
  do {
    b = buf[p++];
    value |= (b & 0x7f) << shift;
    shift += 7;
  } while (b & 0x80 && shift < 35);
  return { value, next: p };
}

export function isDex(buf: Buffer): boolean {
  return buf.length >= 0x70 && buf.toString("latin1", 0, 4) === "dex\n";
}

/** Type descriptors such as `Lcom/example/app/MainActivity;` (primitives and arrays included). */
export function readTypeDescriptors(buf: Buffer): string[] {
  if (!isDex(buf)) return [];
  const stringIdsOff = buf.readUInt32LE(0x3c);
  const typeIdsSize = buf.readUInt32LE(0x40);
  const typeIdsOff = buf.readUInt32LE(0x44);
  const out: string[] = [];
  for (let i = 0; i < typeIdsSize; i++) {
    const t = typeIdsOff + i * 4;
    if (t + 4 > buf.length) break;
    const s = stringIdsOff + buf.readUInt32LE(t) * 4;
    if (s + 4 > buf.length) break;
    const { next } = readUleb128(buf, buf.readUInt32LE(s));
    const end = buf.indexOf(0, next);
    if (end === -1) break;
    out.push(buf.toString("utf8", next, end));
  }
  return out;
}

/**
 * Every string of the dex string pool at least `minLength` UTF-16 units long:
 * the app's constants (URLs, keys, config values) as well as its names.
 */
export function readDexStrings(buf: Buffer, minLength = 16): string[] {
  if (!isDex(buf)) return [];
  const stringIdsSize = buf.readUInt32LE(0x38);
  const stringIdsOff = buf.readUInt32LE(0x3c);
  const out: string[] = [];
  for (let i = 0; i < stringIdsSize; i++) {
    const s = stringIdsOff + i * 4;
    if (s + 4 > buf.length) break;
    const dataOff = buf.readUInt32LE(s);
    if (dataOff >= buf.length) continue;
    const { value: length, next } = readUleb128(buf, dataOff);
    if (length < minLength) continue;
    const end = buf.indexOf(0, next);
    if (end === -1) break;
    out.push(buf.toString("utf8", next, end));
  }
  return out;
}

// Generated by the build for every app; their names say nothing about R8.
const GENERATED = /^(R|R\$.*|BuildConfig|Manifest|Manifest\$.*|databinding\/.*|BR)$/;

export interface ObfuscationVerdict {
  appClasses: number;
  shortNamed: number;
  obfuscated: boolean;
  sample: string[];
}

/**
 * R8/ProGuard renames everything it is allowed to into one- or two-letter
 * names, and usually moves it out of the app package. An unobfuscated build
 * keeps dozens of descriptive classes under the application id.
 */
export function assessDexObfuscation(descriptors: string[], packageName: string): ObfuscationVerdict {
  const prefix = `L${packageName.replace(/\./g, "/")}/`;
  const app = descriptors
    .filter((d) => d.startsWith(prefix) && d.endsWith(";"))
    .map((d) => d.slice(prefix.length, -1))
    .filter((rel) => !GENERATED.test(rel.split("/").pop() ?? ""));
  const simple = (rel: string) => (rel.split("/").pop() ?? "").split("$")[0];
  const shortNamed = app.filter((rel) => simple(rel).length <= 2).length;
  const descriptive = app.filter((rel) => simple(rel).length > 2);
  return {
    appClasses: app.length,
    shortNamed,
    obfuscated: app.length < 25 || shortNamed / app.length >= 0.2,
    sample: descriptive.slice(0, 3).map((rel) => `${packageName}.${rel.replace(/\//g, ".")}`),
  };
}
